/* eslint-disable @wordpress/no-unsafe-wp-apis */

/**
 * WordPress dependencies
 */
import { __ } from '@wordpress/i18n';
import { useState } from '@wordpress/element';
import { useDispatch, useSelect } from '@wordpress/data';
import { store as coreStore } from '@wordpress/core-data';
import { store as noticesStore } from '@wordpress/notices';
import { Button, PanelBody, Spinner, __experimentalVStack as VStack } from '@wordpress/components';

/**
 * Block name, kept here so the site-defaults code has no dependency on edit.js.
 */
const BLOCK_NAME = 'pmp/toc-block';

/**
 * Site option that stores the shared List Items values.
 * Registered with show_in_rest in TocBlock.php so it is part of the site entity.
 */
export const OPTION_NAME = 'pmp_toc_item_defaults';

/**
 * List Items attributes that can be shared site-wide.
 * Sticky and scrollspy are deliberately excluded: they only serve sidebars.
 */
export const ITEM_STYLE_KEYS = [
	'itemBackground',
	'activeBackground',
	'activeColor',
	'activeBorderColor',
	'itemGap',
	'itemPadding',
	'itemBorder',
	'itemRadius',
];

/**
 * Block-level style attributes generated by block supports.
 */
const SUPPORT_STYLE_KEYS = [
	'style',
	'backgroundColor',
	'textColor',
	'gradient',
	'fontSize',
	'fontFamily',
	'borderColor',
];

/**
 * Empty values for a reset.
 */
const EMPTY_ITEM_STYLES = {
	itemBackground: '',
	activeBackground: '',
	activeColor: '',
	activeBorderColor: '',
	itemGap: '',
	itemPadding: {},
	itemBorder: {},
	itemRadius: '',
};

const EMPTY_SUPPORT_STYLES = {
	style: undefined,
	backgroundColor: undefined,
	textColor: undefined,
	gradient: undefined,
	fontSize: undefined,
	fontFamily: undefined,
	borderColor: undefined,
};

/**
 * Whether a value counts as set.
 *
 * @param {*} value Attribute value.
 * @returns {boolean} True when non-empty.
 */
export const isSet = (value) => {
	if (value === undefined || value === null || value === '') {
		return false;
	}
	if (typeof value === 'object') {
		return Object.values(value).some(isSet);
	}
	return true;
};

/**
 * Only the List Items values that are set on an instance.
 *
 * @param {object} attributes Block attributes.
 * @returns {object} Subset of attributes.
 */
export const pickItemStyles = (attributes) =>
	Object.fromEntries(
		ITEM_STYLE_KEYS.filter((key) => isSet(attributes[key])).map((key) => [
			key,
			attributes[key],
		]),
	);

/**
 * Instance values layered over the site-wide defaults.
 *
 * @param {object} attributes Block attributes.
 * @param {object} defaults   Site-wide defaults.
 * @returns {object} Effective List Items values.
 */
export const withItemDefaults = (attributes, defaults) => ({
	...EMPTY_ITEM_STYLES,
	...(defaults || {}),
	...pickItemStyles(attributes),
});

/**
 * Read the site-wide defaults. Editors who cannot manage options get the
 * values printed by TocBlock.php at load time; admins get the live entity so
 * the canvas updates as soon as defaults are applied.
 *
 * @returns {object} Defaults.
 */
export const useItemDefaults = () =>
	useSelect((select) => {
		const canManage = select(coreStore).canUser('update', { kind: 'root', name: 'site' });

		if (canManage) {
			const site = select(coreStore).getEntityRecord('root', 'site');

			if (site && site[OPTION_NAME] !== undefined) {
				return site[OPTION_NAME] || {};
			}
		}

		return window.pmpTocItemDefaults || {};
	}, []);

/**
 * Recursively merge plain objects; values in `source` win.
 *
 * @param {object} target Base object.
 * @param {object} source Overrides.
 * @returns {object} Merged copy.
 */
const deepMerge = (target, source) => {
	const output = { ...(target || {}) };

	Object.entries(source || {}).forEach(([key, value]) => {
		if (value && typeof value === 'object' && !Array.isArray(value)) {
			output[key] = deepMerge(output[key], value);
		} else if (value !== undefined) {
			output[key] = value;
		}
	});

	return output;
};

/**
 * Set a dotted path on an object.
 *
 * @param {object} object Target.
 * @param {string} path   Dotted path.
 * @param {*}      value  Value.
 */
const setPath = (object, path, value) => {
	const keys = path.split('.');
	let cursor = object;

	keys.slice(0, -1).forEach((key) => {
		cursor[key] = cursor[key] && typeof cursor[key] === 'object' ? cursor[key] : {};
		cursor = cursor[key];
	});

	cursor[keys[keys.length - 1]] = value;
};

/**
 * Convert block support attributes into the Global Styles shape for the
 * block, the same way core's "Apply globally" does: preset slugs become
 * `var:preset|…` references and the `style` object is copied as is.
 *
 * @param {object} attributes Block attributes.
 * @returns {object} Global styles fragment.
 */
export const attributesToGlobalStyles = (attributes) => {
	const styles = JSON.parse(JSON.stringify(attributes.style || {}));

	// Legacy Block spacing lives in the List Items defaults instead.
	if (styles.spacing) {
		delete styles.spacing.blockGap;
	}

	const presets = [
		['backgroundColor', 'color.background', 'color'],
		['textColor', 'color.text', 'color'],
		['gradient', 'color.gradient', 'gradient'],
		['fontSize', 'typography.fontSize', 'font-size'],
		['fontFamily', 'typography.fontFamily', 'font-family'],
		['borderColor', 'border.color', 'color'],
	];

	presets.forEach(([attribute, path, presetType]) => {
		if (attributes[attribute]) {
			setPath(styles, path, `var:preset|${presetType}|${attributes[attribute]}`);
		}
	});

	return styles;
};

/**
 * "Site-wide Defaults" panel: pushes this instance's List Items values to the
 * site option and its block-level styles to Global Styles, then clears them
 * on the instance so it follows the shared values.
 *
 * @param {object}   props               Component props.
 * @param {object}   props.attributes    Block attributes.
 * @param {Function} props.setAttributes Attribute setter.
 * @returns {JSX.Element|null} Panel, or null when the user cannot manage the site.
 */
const SiteDefaultsPanel = ({ attributes, setAttributes }) => {
	const [isSaving, setIsSaving] = useState(false);

	const { canManage, globalStylesId } = useSelect(
		(select) => ({
			canManage: select(coreStore).canUser('update', { kind: 'root', name: 'site' }),
			globalStylesId: select(coreStore).__experimentalGetCurrentGlobalStylesId(),
		}),
		[],
	);
	const defaults = useItemDefaults();

	const { saveEntityRecord, editEntityRecord, saveEditedEntityRecord } = useDispatch(coreStore);
	const { createSuccessNotice, createErrorNotice } = useDispatch(noticesStore);

	const hasDefaults = isSet(defaults);
	const hasOwnItemStyles = Object.keys(pickItemStyles(attributes)).length > 0;
	const hasOwnSupportStyles = SUPPORT_STYLE_KEYS.some((key) => isSet(attributes[key]));

	/**
	 * Save shared values, then reset this instance.
	 */
	const applySiteWide = async () => {
		setIsSaving(true);

		try {
			const nextDefaults = { ...(defaults || {}), ...pickItemStyles(attributes) };
			await saveEntityRecord('root', 'site', { [OPTION_NAME]: nextDefaults });

			if (globalStylesId && hasOwnSupportStyles) {
				const record = await window.wp.data
					.resolveSelect('core')
					.getEditedEntityRecord('root', 'globalStyles', globalStylesId);
				const blocks = record?.styles?.blocks || {};
				const merged = deepMerge(blocks[BLOCK_NAME], attributesToGlobalStyles(attributes));

				editEntityRecord('root', 'globalStyles', globalStylesId, {
					styles: {
						...(record?.styles || {}),
						blocks: { ...blocks, [BLOCK_NAME]: merged },
					},
				});
				await saveEditedEntityRecord('root', 'globalStyles', globalStylesId);
			}

			setAttributes({ ...EMPTY_ITEM_STYLES, ...EMPTY_SUPPORT_STYLES });
			createSuccessNotice(
				__('Table of Contents styles applied to every instance.', 'pmp-theme'),
				{ type: 'snackbar' },
			);
		} catch (error) {
			createErrorNotice(
				error?.message || __('Could not save the shared styles.', 'pmp-theme'),
				{ type: 'snackbar' },
			);
		} finally {
			setIsSaving(false);
		}
	};

	/**
	 * Remove the shared List Items values. Global Styles are left as they are
	 * and can be reset from Site Editor > Styles.
	 */
	const clearSiteWide = async () => {
		setIsSaving(true);

		try {
			await saveEntityRecord('root', 'site', { [OPTION_NAME]: {} });
			createSuccessNotice(__('Shared list item styles cleared.', 'pmp-theme'), {
				type: 'snackbar',
			});
		} catch (error) {
			createErrorNotice(
				error?.message || __('Could not clear the shared styles.', 'pmp-theme'),
				{ type: 'snackbar' },
			);
		} finally {
			setIsSaving(false);
		}
	};

	return !canManage ? null : (
		<PanelBody title={__('Site-wide Defaults', 'pmp-theme')} initialOpen={false}>
			<VStack spacing={3}>
				<p>
					{__(
						'Use this instance as the template for every Table of Contents on the site. List item styles are saved as shared defaults; block colors, typography, spacing and border go to Global Styles. This instance is then reset so it follows the shared values. Sticky and highlight settings stay per instance.',
						'pmp-theme',
					)}
				</p>
				<Button
					variant="secondary"
					onClick={applySiteWide}
					disabled={isSaving || (!hasOwnItemStyles && !hasOwnSupportStyles)}
					__next40pxDefaultSize
				>
					{isSaving ? <Spinner /> : null}
					{__('Apply to all Table of Contents blocks', 'pmp-theme')}
				</Button>
				{hasDefaults && (
					<Button
						variant="tertiary"
						isDestructive
						onClick={clearSiteWide}
						disabled={isSaving}
						__next40pxDefaultSize
					>
						{__('Clear shared list item styles', 'pmp-theme')}
					</Button>
				)}
				{!hasOwnItemStyles && !hasOwnSupportStyles && (
					<p className="components-base-control__help">
						{hasDefaults
							? __('This instance is following the shared styles.', 'pmp-theme')
							: __('Style this instance first, then apply.', 'pmp-theme')}
					</p>
				)}
			</VStack>
		</PanelBody>
	);
};

export default SiteDefaultsPanel;
